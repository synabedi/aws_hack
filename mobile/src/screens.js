/* ---------- Site: depth, clock, forecast, verdicts, FloodLab ---------- */
const START = { rainX: 1, kX: 1, pumps: 0, pumpDelayMin: 0 }
const leftText = (t) => (t == null ? 'Not needed' : t === 0 ? 'Already above' : t - RESPONSE_MIN - BUFFER_MIN < 0 ? `Too late by ${Math.round(RESPONSE_MIN + BUFFER_MIN - t)} min` : `${Math.round(t - RESPONSE_MIN - BUFFER_MIN)} min`)

function FloodLab({ state, inputs, onScenario }) {
  const fc = state.latest_forecast
  const thr = state.site.thresholds.closure
  const [o, setO] = useState(START)
  const [remote, setRemote] = useState(null)
  const changed = JSON.stringify(o) !== JSON.stringify(START)
  useEffect(() => { setO(START); setRemote(null) }, [state.site.site_id])
  const base = useMemo(() => (inputs ? runLab(inputs) : fc), [inputs, fc])
  const scn = useMemo(() => (inputs && changed ? runLab(inputs, o) : null), [inputs, o, changed])
  useEffect(() => {
    if (inputs || !o.pumps) { setRemote(null); return }
    let live = true
    api.simulate(state.site.site_id, o.pumps).then((r) => live && setRemote(r))
    return () => { live = false }
  }, [inputs, o.pumps, state.site.site_id])
  const shown = scn || remote
  useEffect(() => { onScenario(shown) }, [shown])
  if (!fc) return <Fine>FloodLab needs a forecast, and this site has no reading yet.</Fine>
  const set = (k, d, lo, hi) => setO((p) => ({ ...p, [k]: Math.min(hi, Math.max(lo, +(p[k] + d).toFixed(2))) }))
  const bT = crossing(base.t, base.depth, thr)
  const sT = shown ? crossing(shown.t, shown.depth, thr) : null
  const two = (a, b) => `${a}  →  ${shown ? b : 'change a control'}`
  return (
    <View>
      {inputs ? <Stepper label="Rainfall" display={`${(inputs.rain_mm_h[0] * o.rainX).toFixed(0)} mm/h`} onMinus={() => set('rainX', -0.25, 0, 2.5)} onPlus={() => set('rainX', 0.25, 0, 2.5)} /> : null}
      {inputs ? <Stepper label="Drain performance" display={`${Math.round(o.kX * 100)}%`} onMinus={() => set('kX', -0.1, 0.1, 1.5)} onPlus={() => set('kX', 0.1, 0.1, 1.5)} /> : null}
      <Stepper label="Pumps sent" display={`${o.pumps}`} onMinus={() => set('pumps', -1, 0, 3)} onPlus={() => set('pumps', 1, 0, 3)} />
      {inputs ? <Stepper label="Pumps arrive after" display={`${o.pumpDelayMin} min`} onMinus={() => set('pumpDelayMin', -5, 0, 30)} onPlus={() => set('pumpDelayMin', 5, 0, 30)} /> : null}
      <View style={{ marginTop: 6 }}>
        <Row label={`Reaches ${thr} cm in`} value={two(bT === 0 ? 'already there' : fmtMin(bT), sT === 0 ? 'already there' : fmtMin(sT))} />
        <Row label="Peak depth, next hour" value={two(`${peak(base.depth).toFixed(0)} cm`, shown && `${peak(shown.depth).toFixed(0)} cm`)} />
        <Row label="Time left to decide" value={two(leftText(bT), leftText(sT))} last />
      </View>
      <Fine>Fitted model on the left, your scenario on the right. The dotted line on the chart is the scenario.{inputs ? '' : ' This site only supports the pump count.'}</Fine>
      {changed ? <View style={{ marginTop: 8, alignSelf: 'flex-start' }}><Btn label="Reset to the fitted model" onPress={() => setO(START)} /></View> : null}
    </View>
  )
}

export function Site({ cur, now }) {
  const { width } = useWindowDimensions()
  const id = cur.site.site_id
  const [readings, setReadings] = useState([])
  const [inputs, setInputs] = useState(null)
  const [scenario, setScenario] = useState(null)
  useEffect(() => {
    let live = true
    setReadings([]); setInputs(null); setScenario(null)
    api.history(id).then((h) => live && setReadings(h))
    api.lab(id).then((l) => live && setInputs(l))
    return () => { live = false }
  }, [id, api.source.mock])
  const r = cur.latest_reading, fc = cur.latest_forecast
  const cv = clockView(cur.clock, fc?.ts, now)
  const d = cur.drain_health
  return (
    <>
      <View style={{ gap: 6 }}>
        <Text style={s.h1}>{cur.site.name}</Text>
        <View style={s.wrap}>
          <Pill kind={cur.site.simulated ? 'sim' : 'pass'}>{cur.site.simulated ? 'Simulated site' : 'Real site'}</Pill>
          <Text style={st.fine}>{r ? `Last reading ${clockTime(r.ts)}` : 'No reading yet'}</Text>
        </View>
        {fc ? <Text style={st.fine}>Rain{inputs ? ` ${inputs.rain_mm_h[0].toFixed(0)} mm/h` : ''}, source {fc.rain_source.replace('scenario:', 'scenario ')}</Text> : null}
      </View>

      <View style={[s.tile, { backgroundColor: C.lilacT }]}>
        <Text style={s.tileL}>Depth at the deepest point</Text>
        <Text style={s.tileN}>{r ? r.max_depth_cm.toFixed(1) : 'None'}{r ? <Text style={s.tileU}> cm</Text> : null}</Text>
        <Text style={s.tileS}>{r ? `± ${(2 * r.sigma_cm).toFixed(1)} cm${r.status !== 'confident' ? ', low confidence' : ''}` : 'Waiting for the first processed frame'}</Text>
      </View>
      <View style={[s.tile, { backgroundColor: TILE[cv.state] }]}>
        <Text style={s.tileL}>Time left to decide</Text>
        <Text style={[s.tileN, cv.state === 'late' && { color: '#b02a28' }]}>{cv.big}</Text>
        <Text style={s.tileS}>{cv.sub}</Text>
      </View>

      <Card title="Depth and forecast">
        {fc ? <Chart width={width - 32 - 36} history={readings.length ? readings : [r]} forecast={fc} thresholds={cur.site.thresholds} scenario={scenario} />
          : <Fine>No forecast yet. It needs at least three confident depth readings from this site.</Fine>}
        {fc ? <Fine>Dots are measured depth with ±2 sigma. The line is the forecast, the shaded band is p10 to p90.</Fine> : null}
      </Card>

      <Card title="Who can still pass">
        <View>
          {cur.verdicts.map((c, i) => {
            const t = c.t_impassable_min
            let kind = 'pass', text = 'Can pass'
            if (c.passable == null) { kind = 'review'; text = r ? 'Manual review' : 'No reading' }
            else if (!c.passable) { kind = 'stop'; text = 'No entry' }
            else if (r && r.max_depth_cm + 2 * r.sigma_cm >= c.threshold_cm) { kind = 'warn'; text = 'Borderline' }
            return (
              <View key={c.vehicle_class} style={[st.row, i === cur.verdicts.length - 1 && { borderBottomWidth: 0 }]}>
                <View style={{ flex: 1 }}>
                  <Text style={s.vName}>{CLASS_LABEL[c.vehicle_class] || c.vehicle_class}<Text style={st.rowN}>  {c.threshold_cm} cm limit{c.assumed ? ', assumed' : ''}</Text></Text>
                  <Text style={st.fine}>{c.passable == null ? 'No automatic verdict' : !c.passable ? 'Above limit' : t == null ? 'Not reached in 60 min' : `Blocked in ${fmtMin(t)}`}</Text>
                </View>
                <Pill kind={kind}>{text}</Pill>
              </View>
            )
          })}
        </View>
      </Card>

      <Card title="How the clock is worked out"><ClockRows clock={cur.clock} /></Card>
      <Card title="FloodLab: change the conditions"><FloodLab state={cur} inputs={inputs} onScenario={setScenario} /></Card>

      <Card title="Camera view">
        <Fine>{cur.site.simulated ? 'No camera at a simulated site. Depth is replayed from the site model, so there is no frame to show.'
          : 'No frame yet. The camera frame, water mask and depth map appear here once the staged flood footage is processed.'}</Fine>
      </Card>
      <Card title="Drain health">
        {d ? <>
          <View style={s.meter}><View style={{ width: `${Math.min(d.score_pct, 100)}%`, height: '100%', backgroundColor: d.flagged ? C.red : C.green, borderRadius: 99 }} /></View>
          <Fine>Draining at {d.score_pct.toFixed(0)}% of its best observed rate. k {d.k.toFixed(4)}, interval {d.k_ci[0].toFixed(4)} to {d.k_ci[1].toFixed(4)}.{d.flagged ? ' Flagged.' : ''}</Fine>
        </> : <Fine>No recession fitted yet. Needs one drain-down after the water stops rising.</Fine>}
      </Card>
    </>
  )
}

/* ---------- Approvals: the officer signs every closure ---------- */
function Advisory({ a }) {
  if (!a.payload?.advisory_en && !a.payload?.advisory_hi) return null
  return (
    <View style={s.adv}>
      {a.payload.advisory_hi ? <Text style={s.hi}>{a.payload.advisory_hi}</Text> : null}
      {a.payload.advisory_en ? <Text style={s.en}>{a.payload.advisory_en}</Text> : null}
    </View>
  )
}
const TYPE = { closure: 'closure', reopen: 'reopening', pump_move: 'pump move', advisory: 'advisory' }

export function Approvals({ actions, ranked, officer, setOfficer, onDecide, busy }) {
  const name = (id) => ranked.find((x) => x.site.site_id === id)?.site.name || id
  const open = actions.filter((a) => a.status === 'proposed')
  const done = actions.filter((a) => a.status !== 'proposed').sort((a, b) => (b.decided_at || b.published_at || 0) - (a.decided_at || a.published_at || 0))
  const id = officer.trim()
  return (
    <>
      <Text style={s.h1}>Closures waiting for you</Text>
      <Card>
        <Text style={st.rowL}>Officer ID. Every decision is logged against it.</Text>
        <TextInput value={officer} onChangeText={setOfficer} placeholder="PWD-NO-014" placeholderTextColor={C.mute} autoCapitalize="characters" style={s.input} accessibilityLabel="Officer ID" />
      </Card>
      {!open.length ? <Card><Fine>Nothing is waiting for a decision. A closure is proposed when a site is at the closure rule or within 20 minutes of it.</Fine></Card> : null}
      {open.map((a) => {
        const low = a.reading_status !== 'confident'
        return (
          <Card key={a.action_id}>
            <Text style={s.siteName}>{name(a.site_id)}</Text>
            <View style={s.wrap}>{a.simulated ? <Pill kind="sim">Simulated</Pill> : null}<Pill kind="warn">Proposed {TYPE[a.type] || a.type}</Pill>{low ? <Pill kind="review">Low-confidence reading</Pill> : null}</View>
            <Text style={s.en}>{a.justification}</Text>
            <Fine>Draft advisory, published only if you approve:</Fine>
            <Advisory a={a} />
            <View style={{ flexDirection: 'row', gap: 8 }}>
              <Btn primary label="Approve and publish" disabled={!id || busy || low} onPress={() => onDecide(a, 'approve')} />
              <Btn label="Reject" disabled={!id || busy} onPress={() => onDecide(a, 'reject')} />
            </View>
            {low ? <Fine>Policy blocks approval on a low-confidence reading. Check the frame yourself.</Fine> : !id ? <Fine>Enter your officer ID above to decide.</Fine> : null}
          </Card>
        )
      })}
      {done.length ? <Text style={s.h3}>Decision log</Text> : null}
      {done.map((a) => (
        <Card key={a.action_id}>
          <Text style={s.siteName}>{name(a.site_id)}</Text>
          <View style={s.wrap}>{a.simulated ? <Pill kind="sim">Simulated</Pill> : null}
            <Pill kind={a.status === 'rejected' ? 'review' : 'pass'}>{a.status === 'rejected' ? 'Rejected' : a.approved_by ? 'Approved and published' : 'Published automatically'}</Pill></View>
          <Fine>{a.approved_by ? `${a.status === 'rejected' ? 'Rejected' : 'Approved'} by ${a.approved_by} at ${clockTime(a.decided_at)}` : `${a.justification} Published at ${clockTime(a.published_at)}.`}</Fine>
          {a.status !== 'rejected' ? <Advisory a={a} /> : null}
        </Card>
      ))}
    </>
  )
}

/* ---------- Pumps: forecast plan against the simple baseline ---------- */
export function Pumps({ allocation, ranked, onOpen }) {
  if (!allocation) return <><Text style={s.h1}>Pump plan</Text><Card><Fine>No pump allocation round has run yet.</Fine></Card></>
  const a = allocation
  const gain = a.benefit_minutes - a.baseline_benefit_minutes
  const rows = [...ranked].sort((x, y) => (a.awards[y.site.site_id] || 0) - (a.awards[x.site.site_id] || 0))
  const dots = (n) => (n ? <View style={{ flexDirection: 'row', gap: 4 }}>{Array.from({ length: n }, (_, i) => <View key={i} style={s.pump} />)}</View> : <Text style={st.fine}>None</Text>)
  return (
    <>
      <Text style={s.h1}>Pump plan</Text>
      <View style={[s.tile, { backgroundColor: C.aquaT }]}>
        <Text style={s.tileL}>Planned on the forecast</Text>
        <Text style={s.tileN}>{a.benefit_minutes.toFixed(0)}<Text style={s.tileU}> site-min avoided</Text></Text>
        <Text style={s.tileS}>Baseline, pumps to the deepest sites now: {a.baseline_benefit_minutes.toFixed(0)}. Difference {gain >= 0 ? '+' : ''}{gain.toFixed(0)} with the same {a.inventory.pumps} pumps. A result of this simulation, not a general claim.</Text>
      </View>
      <Card title="Where each pump goes">
        <View style={[st.row, { paddingTop: 0 }]}><Text style={[st.fine, { flex: 1 }]}>Site</Text><Text style={[st.fine, s.col]}>Forecast plan</Text><Text style={[st.fine, s.col]}>Baseline</Text></View>
        {rows.map((x, i) => (
          <Pressable key={x.site.site_id} onPress={() => onOpen(x.site.site_id)} style={[st.row, i === rows.length - 1 && { borderBottomWidth: 0 }]}>
            <View style={{ flex: 1 }}>
              <Text style={s.vName}>{short(x.site.name)}</Text>
              <Text style={st.fine}>{x.latest_reading ? `${x.latest_reading.max_depth_cm.toFixed(0)} cm now` : 'No reading'}, traffic weight {x.site.traffic_weight.toFixed(1)}</Text>
            </View>
            <View style={s.col}>{dots(a.awards[x.site.site_id] || 0)}</View>
            <View style={s.col}>{dots(a.baseline_awards[x.site.site_id] || 0)}</View>
          </Pressable>
        ))}
        <Fine>The allocation is computed in code. The agent only explains it, and moving a pump still needs an officer's approval. All sites in this round are simulated.</Fine>
      </Card>
    </>
  )
}

